#!/usr/bin/env python3
"""session-telemetry.py — 無狀態 Claude Code Session 遙測週報工具（零 LLM、零常駐 DB）。

有界兩層流式掃描 --projects-dir（預設 ~/.claude/projects）下的主 session *.jsonl
與對應 <session-id>/subagents/*.jsonl / *.meta.json，產出 4 組可行動指標與品質收據：
  1. 真人純主控（排除 worktree/Herdr worker 與自動 sdk-cli/tmp 測試）僅程式碼自改 ÷ 實作派工比＋近 M 個月趨勢
  2. 審查後 60 分鐘內純主控連環自改案數（純 5 程式碼審查子代理回報後 60m 內未派實作且連續改程式碼 ≥ 3 次）
  3. 真人互動委派角色佔比（判斷類 / 審查驗證類 / 實作類 / 偵察類 / 其他）
  4. 真人互動 Token 四分拆（input / cache_creation / cache_read / output，分列主 session 與 subagent，強調純 output 佔比）
     與模型族群佔比（opus/pro vs argon vs gpt vs sonnet/flash vs haiku vs other）
  5. 尾段「觀測口徑與品質收據」

用法：
  python3 session-telemetry.py [--projects-dir DIR] [--days 30] [--trend-months 4] [--date YYYY-MM-DD] [--format markdown|json]
"""

