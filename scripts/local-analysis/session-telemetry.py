def recent_month_keys(ref_date: dt.date, count: int) -> list:
    y, m = ref_date.year, ref_date.month
    keys = []
    for _ in range(count):
        keys.append(f"{y:04d}-{m:02d}")
        m -= 1
        if m == 0:
            m = 12
            y -= 1
    keys.reverse()
    return keys


def _to_int(val) -> int:
    if val is None or isinstance(val, bool):
        return 0
    try:
        return int(val)
    except (ValueError, TypeError):
        return 0


def _pick_model(primary: str, secondary: str) -> str:
    if primary and primary != "<synthetic>":
        return primary
    if secondary and secondary != "<synthetic>":
        return secondary
    return primary or secondary


def _local_midnight_ts(d: dt.date) -> float:
    return dt.datetime.combine(d, dt.time.min).astimezone().timestamp()


def _local_dt_from_ts(ts: float, local_tz=None) -> dt.datetime:
    if local_tz is not None:
        return dt.datetime.fromtimestamp(ts, tz=local_tz)
    return dt.datetime.fromtimestamp(ts).astimezone()


def _merge_usage(msg_usage: dict, anon_usage: list, file_path_str: str, line_no: int, model: str, u: dict, mid):
    vals = (
        _to_int(u.get("input_tokens")),
        _to_int(u.get("cache_creation_input_tokens")),
        _to_int(u.get("cache_read_input_tokens")),
        _to_int(u.get("output_tokens")),
    )
    if isinstance(mid, str) and mid:
        prev = msg_usage.get(mid)
        if prev is None:
            msg_usage[mid] = (model, vals[0], vals[1], vals[2], vals[3])
        else:
            msg_usage[mid] = (
                _pick_model(model, prev[0]),
                max(prev[1], vals[0]),
                max(prev[2], vals[1]),
                max(prev[3], vals[2]),
                max(prev[4], vals[3]),
            )
    else:
        anon_usage.append(((file_path_str, line_no), model, vals[0], vals[1], vals[2], vals[3]))


def parse_subagent_jsonl(sf: Path, collect_usage: bool = True) -> dict:
    msg_usage = {}
    anon_usage = []
    parse_errors = 0
    sf_str = str(sf)

    try:
        with sf.open("rb") as fh:
            for line_no, raw in enumerate(fh, 1):
                if not raw.strip():
                    continue
                is_asst = b'"type":"assistant"' in raw or b'"type": "assistant"' in raw
                if not is_asst:
                    if raw.lstrip().startswith(b"{") and b'"type"' in raw:
                        continue
                try:
                    obj = json.loads(raw)
                except Exception:
                    parse_errors += 1
                    continue
                if not isinstance(obj, dict):
                    parse_errors += 1
                    continue
                if not collect_usage or obj.get("type") != "assistant":
                    continue
                msg = obj.get("message")
                if not isinstance(msg, dict):
                    continue
                model = str(msg.get("model") or "")
                u = msg.get("usage")
                if isinstance(u, dict):
                    _merge_usage(msg_usage, anon_usage, sf_str, line_no, model, u, msg.get("id"))
    except OSError:
        return {"skipped": True, "msg_usage": {}, "anon_usage": [], "parse_errors": parse_errors}

    return {
        "skipped": False,
        "msg_usage": msg_usage,
        "anon_usage": anon_usage,
        "parse_errors": parse_errors,
    }


def extract_pure_5_bursts(events: list, sid: str, pname: str, is_worker: bool, fallback_ts: float, local_tz=None) -> list:
    bursts = []
    in_pr = False
    cur_roles = []
    cur_ts = 0.0
    cnt = 0
    cnt60 = 0
    files = set()
    files60 = set()

    def flush():
        nonlocal cnt, cnt60, files, files60
        if in_pr and cnt >= 3:
            bursts.append({
                "sid8": sid[:8],
                "date": _local_dt_from_ts(cur_ts or fallback_ts, local_tz).strftime("%Y-%m-%d"),
                "project": short_project_name(pname),
                "is_worker_session": is_worker,
                "roles": sorted(set(cur_roles)),
                "code_edits": cnt,
                "distinct_files": len(files),
                "code_edits_within_60m": cnt60,
                "distinct_files_within_60m": len(files60),
                "sample_files": sorted(files60 or files)[:6],
            })
        cnt = 0
        cnt60 = 0
        files = set()
        files60 = set()

    for ts, kind, det, extra in events:
        if kind == "REVIEW" and det in PURE_CODE_REVIEW_ROLES:
            if cnt > 0:
                flush()
                cur_roles = [det]
            else:
                cur_roles.append(det)
            in_pr = True
            cur_ts = ts
        elif kind == "IMPL_DISPATCH":
            if in_pr:
                flush()
                in_pr = False
                cur_roles = []
        elif kind == "EDIT" and det == "code" and in_pr:
            cnt += 1
            if extra:
                files.add(extra)
            if 0 <= (ts - cur_ts) <= 3600:
                cnt60 += 1
                if extra:
                    files60.add(extra)

    if in_pr:
        flush()
    return bursts


def process_session(task: tuple) -> dict:
    fpath_str, mtime = task[0], task[1]
    window_start = task[2] if len(task) >= 4 else None
    anchor_end = task[3] if len(task) >= 4 else None
    fpath = Path(fpath_str)
    pname = fpath.parent.name
    sid = fpath.stem
    proj_cat = classify_project_dir(pname)
    is_worktree = "worktree" in pname.lower()

    msg_usage = {}
    anon_usage = []
    seen_tool_ids = set()

    entrypoints = Counter()
    human_typed_turns = 0
    human_fallback_turns = 0
    worker_like_first_prompt = False
    first_human_checked = False
    first_ts = 0.0
    last_ts = 0.0

    edit_records = []
    review_records = []
    impl_events = []
    tool_results = {}
    pending_tid_bytes = set()
    delegations_main = []
    edits_all = 0
    edits_code = 0
    edits_config = 0
    edits_non_code = 0
    parse_errors = 0

    try:
        with fpath.open("rb") as fh:
            for line_no, raw in enumerate(fh, 1):
                if not raw.strip():
                    continue
                is_asst = b'"type":"assistant"' in raw or b'"type": "assistant"' in raw
                is_user = (not is_asst) and (b'"type":"user"' in raw or b'"type": "user"' in raw)
                if not is_asst and not is_user:
                    if raw.lstrip().startswith(b"{") and b'"type"' in raw:
                        continue

                # 超大 tool_result 行若不含待配對的編輯／審查 tool_use_id 才略過，避免漏接大型審查回報或編輯錯誤
                if is_user and len(raw) > 32768 and raw.lstrip().startswith(b"{"):
                    if (
                        (b'"type":"tool_result"' in raw or b'"type": "tool_result"' in raw)
                        and b'"promptSource":"typed"' not in raw
                        and b'"promptSource": "typed"' not in raw
                        and b'"turnOrigin":"human"' not in raw
                        and b'"turnOrigin": "human"' not in raw
                        and not (pending_tid_bytes and any(tb in raw for tb in pending_tid_bytes))
                    ):
                        continue

                try:
                    obj = json.loads(raw)
                except Exception:
                    parse_errors += 1
                    continue
                if not isinstance(obj, dict):
                    parse_errors += 1
                    continue

                rtype = obj.get("type")
                ts = parse_iso_ts(obj.get("timestamp"))
                if ts > 0:
                    if first_ts == 0.0 or ts < first_ts:
                        first_ts = ts
                    if ts > last_ts:
                        last_ts = ts

                if rtype == "user":
                    ep = str(obj.get("entrypoint") or "")
                    if ep:
                        entrypoints[ep] += 1
                    ps = obj.get("promptSource")
                    to = obj.get("turnOrigin")
                    orig = obj.get("origin")
                    orig_kind = orig.get("kind") if isinstance(orig, dict) else None
                    is_meta = bool(obj.get("isMeta"))
                    is_side = bool(obj.get("isSidechain"))

                    raw_msg = obj.get("message")
                    msg = raw_msg if isinstance(raw_msg, dict) else {}
                    content = msg.get("content")
                    text = ""
                    has_tool_result = False
                    if isinstance(content, str):
                        text = content
                    elif isinstance(content, list):
                        parts = []
                        for blk in content:
                            if isinstance(blk, dict):
                                bt = blk.get("type")
                                if bt == "tool_result":
                                    has_tool_result = True
                                    raw_tuid = blk.get("tool_use_id")
                                    tuid = raw_tuid if isinstance(raw_tuid, str) else ""
                                    if tuid:
                                        if tuid not in tool_results:
                                            tool_results[tuid] = (ts or mtime, line_no, blk.get("is_error") is True)
                                        pending_tid_bytes.discard(tuid.encode("utf-8"))
                                elif bt == "text" and isinstance(blk.get("text"), str) and blk["text"]:
                                    parts.append(blk["text"])
                        text = "\n".join(parts)

                    is_explicit_human = (
                        ps in ("typed", "queued", "suggestion_accepted")
                        or to == "human"
                        or orig_kind == "human"
                    )
                    if is_explicit_human:
                        human_typed_turns += 1
                        t0 = text.strip()
                        if not first_human_checked and t0:
                            first_human_checked = True
                            if t0.startswith(WORKER_PROMPT_PREFIXES):
                                worker_like_first_prompt = True
                    elif (
                        ep == "cli"
                        and not is_meta
                        and not is_side
                        and not has_tool_result
                        and ps is None
                        and to is None
                    ):
                        t0 = text.strip()
                        if t0 and not any(t0.startswith(pfx) for pfx in SYSTEM_USER_PREFIXES):
                            human_fallback_turns += 1
                            if not first_human_checked:
                                first_human_checked = True
                                if t0.startswith(WORKER_PROMPT_PREFIXES):
                                    worker_like_first_prompt = True

                elif rtype == "assistant":
                    msg = obj.get("message")
                    if not isinstance(msg, dict):
                        continue
                    model = str(msg.get("model") or "")
                    u = msg.get("usage")
                    if isinstance(u, dict):
                        _merge_usage(msg_usage, anon_usage, fpath_str, line_no, model, u, msg.get("id"))

                    content = msg.get("content")
                    if isinstance(content, list):
                        for blk in content:
                            if not isinstance(blk, dict) or blk.get("type") != "tool_use":
                                continue
                            tid = blk.get("id")
                            tid_s = tid if isinstance(tid, str) else ""
                            if tid_s:
                                if tid_s in seen_tool_ids:
                                    continue
                                seen_tool_ids.add(tid_s)
                            tn = blk.get("name", "")
                            inp = blk.get("input") or {}
                            if not isinstance(inp, dict):
                                inp = {}

                            if tn in EDIT_TOOLS:
                                fp = str(inp.get("file_path") or inp.get("notebook_path") or "")
                                fcat = classify_file_path(fp)
                                fkey = "/".join(fp.split("/")[-3:]) if fp else ""
                                edit_records.append((tid_s, ts or mtime, line_no, fcat, fkey))
                                if tid_s:
                                    pending_tid_bytes.add(tid_s.encode("utf-8"))

                            elif tn in ("Agent", "Task"):
                                stype = str(inp.get("subagent_type") or inp.get("agent") or "general-purpose")
                                delegations_main.append((tn, stype, tid_s))
                                if stype in PURE_CODE_REVIEW_ROLES and tid_s:
                                    review_records.append((tid_s, stype))
                                    pending_tid_bytes.add(tid_s.encode("utf-8"))
                                elif stype in IMPL_ROLES:
                                    impl_events.append((ts or mtime, line_no, "IMPL_DISPATCH", stype, tid_s, tid_s))
    except OSError:
        return {"skipped": True, "path": fpath_str, "mtime": mtime, "last_ts": 0.0, "parse_errors": parse_errors}

    ordered_events = list(impl_events)
    valid_edits = []
    for tid_s, ets, lno, fcat, fkey in edit_records:
        tr = tool_results.get(tid_s) if tid_s else None
        if tr is not None and tr[2]:
            continue
        edits_all += 1
        if fcat == "code":
            edits_code += 1
        elif fcat == "config":
            edits_config += 1
        else:
            edits_non_code += 1
        valid_edits.append((tid_s, fcat))
        ordered_events.append((ets, lno, "EDIT", fcat, fkey, tid_s))

    for tid_s, stype in review_records:
        tr = tool_results.get(tid_s)
        if tr is None or tr[2]:
            continue
        rts, rlno, _ = tr
        ordered_events.append((rts, rlno, "REVIEW", stype, tid_s, tid_s))

    ordered_events.sort(key=lambda x: (x[0], x[1]))
    events = [(e[0], e[2], e[3], e[4]) for e in ordered_events]
    events_with_tid = [(e[0], e[2], e[3], e[4], e[5]) for e in ordered_events]

    total_human_turns = human_typed_turns + human_fallback_turns
    is_human = (human_typed_turns > 0) if proj_cat in ("tmp", "var-folders") else (total_human_turns > 0)
    is_worker_session = is_human and (is_worktree or worker_like_first_prompt)

    ref_ts = last_ts if last_ts > 0 else mtime
    in_usage_window = (
        window_start is None
        or anchor_end is None
        or (window_start <= ref_ts < anchor_end and not (last_ts > 0 and last_ts >= anchor_end))
    )
    need_usage = is_human and in_usage_window
    if not need_usage:
        msg_usage = {}
        anon_usage = []

    sub_dir = fpath.parent / sid / "subagents"
    sub_msg_usage = {}
    sub_anon_usage = []
    sub_cross_file_deduped = 0
    sub_meta_types = Counter()
    sub_jsonl_count = 0
    sub_skipped = 0
    sub_tool_use_ids = set()

    if sub_dir.is_dir():
        metas = {}
        jsonls = {}
        try:
            for sf in sub_dir.iterdir():
                if not sf.is_file():
                    continue
                if sf.name.endswith(".meta.json"):
                    stem = sf.name[:-len(".meta.json")]
                    try:
                        loaded_meta = json.loads(sf.read_text(encoding="utf-8", errors="replace"))
                        metas[stem] = loaded_meta if isinstance(loaded_meta, dict) else {}
                    except Exception:
                        metas[stem] = {}
                elif sf.suffix == ".jsonl":
                    sub_jsonl_count += 1
                    jsonls[sf.stem] = sf
        except OSError:
            pass

        for stem in sorted(set(metas.keys()) | set(jsonls.keys())):
            raw_meta = metas.get(stem)
            meta = raw_meta if isinstance(raw_meta, dict) else {}
            if stem in metas:
                atype = str(meta.get("agentType") or "<no-meta>")
                sub_meta_types[atype] += 1
                tuid = meta.get("toolUseId")
                if isinstance(tuid, str) and tuid:
                    sub_tool_use_ids.add(tuid)
            sf = jsonls.get(stem)
            if sf is not None:
                sr = parse_subagent_jsonl(sf, collect_usage=need_usage)
                parse_errors += sr.get("parse_errors", 0)
                if sr.get("skipped"):
                    sub_skipped += 1
                elif need_usage:
                    for mid, vals in sr["msg_usage"].items():
                        prev = sub_msg_usage.get(mid)
                        if prev is None:
                            sub_msg_usage[mid] = vals
                        else:
                            sub_cross_file_deduped += 1
                            sub_msg_usage[mid] = (
                                _pick_model(prev[0], vals[0]),
                                max(prev[1], vals[1]),
                                max(prev[2], vals[2]),
                                max(prev[3], vals[3]),
                                max(prev[4], vals[4]),
                            )
                    sub_anon_usage.extend(sr["anon_usage"])

    if not is_human:
        if entrypoints.get("sdk-cli", 0) > 0:
            auto_reason = "sdk-cli"
        elif proj_cat in ("tmp", "var-folders"):
            auto_reason = "tmp-harness"
        else:
            auto_reason = "cli-zero-human-turns"
    else:
        auto_reason = "human-worker" if is_worker_session else "human-direct"

    main_agent_tids = {t[2] for t in delegations_main if t[0] in ("Agent", "Task") and t[2]}
    matched_tids = len(main_agent_tids & sub_tool_use_ids)

    return {
        "skipped": False,
        "mtime": mtime,
        "first_ts": first_ts,
        "last_ts": last_ts,
        "sid": sid,
        "pname": pname,
        "is_human": is_human,
        "is_worker_session": is_worker_session,
        "auto_reason": auto_reason,
        "main_msg_usage": msg_usage,
        "main_anon_usage": anon_usage,
        "sub_msg_usage": sub_msg_usage,
        "sub_anon_usage": sub_anon_usage,
        "sub_cross_file_deduped": sub_cross_file_deduped,
        "delegations_main": [(d[0], d[1]) for d in delegations_main],
        "delegations_main_full": delegations_main,
        "sub_meta_types": dict(sub_meta_types),
        "sub_jsonl_count": sub_jsonl_count,
        "sub_skipped": sub_skipped,
        "matched_tids": matched_tids,
        "main_agent_tid_cnt": len(main_agent_tids),
        "main_agent_tids": main_agent_tids,
        "sub_tool_use_ids": sub_tool_use_ids,
        "edits_all": edits_all,
        "edits_code": edits_code,
        "edits_config": edits_config,
        "edits_non_code": edits_non_code,
        "valid_edits": valid_edits,
        "events": events,
        "events_with_tid": events_with_tid,
        "parse_errors": parse_errors,
    }


def add_vec(dst: list, src: list):
    dst[0] += src[0]
    dst[1] += src[1]
    dst[2] += src[2]
    dst[3] += src[3]


def pct(n: int, d: int) -> float:
    return round(100.0 * n / d, 2) if d else 0.0


def ratio(n: int, d: int):
    return round(n / d, 2) if d else None


def fmt_token_block(arr: list) -> dict:
    total = sum(arr)
    return {
        "input_tokens": arr[0],
        "cache_creation_input_tokens": arr[1],
        "cache_read_input_tokens": arr[2],
        "output_tokens": arr[3],
        "total": total,
        "pure_output_pct": pct(arr[3], total),
    }


def analyze_projects(
    projects_dir: Path,
    days: int = 30,
    trend_months: int = 4,
    ref_date: dt.date = None,
    workers: int = 1,
) -> dict:
    t0 = time.time()
    if ref_date is None:
        ref_date = dt.datetime.now().astimezone().date()

    window_start_date = ref_date - dt.timedelta(days=days - 1)
    anchor_end = _local_midnight_ts(ref_date + dt.timedelta(days=1))
    window_start = _local_midnight_ts(window_start_date)

    trend_month_list = recent_month_keys(ref_date, trend_months)
    trend_month_set = set(trend_month_list)
    first_y, first_m = map(int, trend_month_list[0].split("-"))
    trend_start = _local_midnight_ts(dt.date(first_y, first_m, 1))
    scan_start = min(window_start, trend_start)

    tasks = []
    total_all_time = 0
    skipped_main = 0

    for pd in sorted(projects_dir.iterdir()):
        if not pd.is_dir() or pd.name in NON_SESSION_PROJECT_DIRS:
            continue
        try:
            entries = sorted(pd.iterdir())
        except OSError:
            continue
        for f in entries:
            if not (f.is_file() and f.suffix == ".jsonl"):
                continue
            total_all_time += 1
            try:
                st = f.stat()
            except OSError:
                skipped_main += 1
                continue
            if st.st_mtime >= scan_start:
                tasks.append((str(f), st.st_mtime, window_start, anchor_end))

    if workers > 1 and len(tasks) >= 64:
        with ProcessPoolExecutor(max_workers=workers) as ex:
            results = list(ex.map(process_session, tasks, chunksize=32))
    else:
        results = [process_session(t) for t in tasks]

    # Aggregators for primary --days window
    win_sessions_total = 0
    win_sessions_human = 0
    win_sessions_auto = 0
    win_auto_by_reason = Counter()
    win_sub_jsonl = 0
    skipped_sub = 0
    parse_errors_total = 0
    scanned_in_range = 0
    win_matched_tids_set = set()
    win_main_tids_set = set()
    win_human_matched_tids_set = set()
    win_human_main_tids_set = set()
    win_sub_tids_all = set()
    win_human_sub_tids = set()
    win_seen_edit_tids = set()
    win_seen_deleg_tids = set()
    trend_seen_edit_tids = set()
    trend_seen_impl_tids = set()

    orch = {"sessions": 0, "edits_code": 0, "edits_config": 0, "edits_non_code": 0, "edits_all": 0, "impl_dispatches": 0}
    wrk = {"sessions": 0, "edits_code": 0, "edits_config": 0, "edits_non_code": 0, "edits_all": 0, "impl_dispatches": 0}

    orch_bursts_all = []
    role_main_cats = Counter()
    role_sub_meta_cats = Counter()
    top_agent_types = Counter()

    # 跨檔全域去重表：key = message.id（無 ID 時為 (file_path, line_no)），value = (source, model, i, cc, cr, o)
    global_msg_usage = {}
    cross_file_deduped_messages = 0
    tokens_main = [0, 0, 0, 0]
    tokens_sub = [0, 0, 0, 0]
    tokens_by_family = {fam: [0, 0, 0, 0] for fam in MODEL_FAMILY_ORDER}

    # Trend aggregator (pure orchestrator only, per month)
    trend_by_month = {mk: {"sessions": 0, "edits_code": 0, "impl_dispatches": 0} for mk in trend_month_list}

    for res in results:
        parse_errors_total += res.get("parse_errors", 0)
        if res.get("skipped"):
            skipped_main += 1
            continue
        skipped_sub += res.get("sub_skipped", 0)

        last_ts = res["last_ts"]
        ref_ts = last_ts if last_ts > 0 else res["mtime"]
        # 如果明確有 JSONL timestamp 且晚於 --date 當天結束，排除在該基準日報告之外
        if last_ts > 0 and last_ts >= anchor_end:
            continue

        ref_dt = _local_dt_from_ts(ref_ts)
        month_key = ref_dt.strftime("%Y-%m")
        in_window = (window_start <= ref_ts < anchor_end)
        in_trend = (ref_ts < anchor_end) and (month_key in trend_month_set)

        if not in_window and not in_trend:
            continue

        scanned_in_range += 1
        delegs_full = res.get("delegations_main_full")
        if delegs_full is None:
            delegs_full = [(tn, stype, "") for tn, stype in res["delegations_main"]]
        valid_edits = res.get("valid_edits")

        # Monthly trend (Metric 1): pure orchestrator only（跨檔 tool_use_id 去重）
        if in_trend and res["is_human"] and not res["is_worker_session"]:
            mm = trend_by_month[month_key]
            mm["sessions"] += 1
            if valid_edits is not None:
                for tid_s, fcat in valid_edits:
                    if tid_s:
                        if tid_s in trend_seen_edit_tids:
                            continue
                        trend_seen_edit_tids.add(tid_s)
                    if fcat == "code":
                        mm["edits_code"] += 1
            else:
                mm["edits_code"] += res["edits_code"]
            for tn, stype, tid_s in delegs_full:
                if tn in ("Agent", "Task") and classify_role(stype) == "impl":
                    if tid_s:
                        if tid_s in trend_seen_impl_tids:
                            continue
                        trend_seen_impl_tids.add(tid_s)
                    mm["impl_dispatches"] += 1

        if not in_window:
            continue

        win_sessions_total += 1
        win_sub_jsonl += res["sub_jsonl_count"]
        res_main_tids = res.get("main_agent_tids", set())
        res_sub_tids = res.get("sub_tool_use_ids", set())
        win_main_tids_set.update(res_main_tids)
        win_sub_tids_all.update(res_sub_tids)
        win_matched_tids_set.update(res_main_tids & res_sub_tids)

        if not res["is_human"]:
            win_sessions_auto += 1
            win_auto_by_reason[res["auto_reason"]] += 1
            continue

        win_sessions_human += 1
        win_human_main_tids_set.update(res_main_tids)
        win_human_sub_tids.update(res_sub_tids)
        win_human_matched_tids_set.update(res_main_tids & res_sub_tids)

        # Metric 1: orchestrator vs worker split（跨檔 tool_use_id 去重）
        slot = wrk if res["is_worker_session"] else orch
        slot["sessions"] += 1
        session_fresh_edit_tids = set()
        if valid_edits is not None:
            for tid_s, fcat in valid_edits:
                if tid_s:
                    if tid_s in win_seen_edit_tids:
                        continue
                    win_seen_edit_tids.add(tid_s)
                    session_fresh_edit_tids.add(tid_s)
                slot["edits_all"] += 1
                if fcat == "code":
                    slot["edits_code"] += 1
                elif fcat == "config":
                    slot["edits_config"] += 1
                else:
                    slot["edits_non_code"] += 1
        else:
            slot["edits_code"] += res["edits_code"]
            slot["edits_config"] += res["edits_config"]
            slot["edits_non_code"] += res["edits_non_code"]
            slot["edits_all"] += res["edits_all"]

        # Metric 3 & impl_dispatches: human interactive delegation roles（跨檔 tool_use_id 去重）
        for tn, stype, tid_s in delegs_full:
            if tn not in ("Agent", "Task"):
                continue
            if tid_s:
                if tid_s in win_seen_deleg_tids:
                    continue
                win_seen_deleg_tids.add(tid_s)
            cat = classify_role(stype)
            role_main_cats[cat] += 1
            top_agent_types[stype] += 1
            if cat == "impl":
                slot["impl_dispatches"] += 1

        # Metric 2: post-review bursts on pure orchestrator（排除已於他檔計過的重複編輯 tid）
        if not res["is_worker_session"]:
            ev_with_tid = res.get("events_with_tid")
            if ev_with_tid is not None:
                burst_events = [
                    (ets, kind, det, extra)
                    for ets, kind, det, extra, tid_s in ev_with_tid
                    if kind != "EDIT" or not tid_s or tid_s in session_fresh_edit_tids
                ]
            else:
                burst_events = res["events"]
            bursts = extract_pure_5_bursts(
                burst_events, res["sid"], res["pname"], False, ref_ts
            )
            orch_bursts_all.extend(bursts)

        for atype, cnt in res["sub_meta_types"].items():
            role_sub_meta_cats[classify_role(atype)] += cnt

        # Metric 4: 跨檔全域去重（保留首次來源與模型族群歸屬一致性）
        cross_file_deduped_messages += res.get("sub_cross_file_deduped", 0)
        for src, msg_map, anon_list in (
            ("main", res["main_msg_usage"], res["main_anon_usage"]),
            ("sub", res["sub_msg_usage"], res["sub_anon_usage"]),
        ):
            for mid, (model, i, cc, cr, o) in msg_map.items():
                prev = global_msg_usage.get(mid)
                if prev is None:
                    global_msg_usage[mid] = (src, model, i, cc, cr, o)
                else:
                    cross_file_deduped_messages += 1
                    psrc, pm, pi, pcc, pcr, po = prev
                    global_msg_usage[mid] = (
                        psrc,
                        _pick_model(pm, model),
                        max(pi, i),
                        max(pcc, cc),
                        max(pcr, cr),
                        max(po, o),
                    )
            for anon_key, model, i, cc, cr, o in anon_list:
                global_msg_usage[anon_key] = (src, model, i, cc, cr, o)

    win_main_tids = len(win_main_tids_set)
    win_matched_tids = len(win_matched_tids_set | (win_main_tids_set & win_sub_tids_all))
    win_human_main_tids = len(win_human_main_tids_set)
    win_human_matched_tids = len(win_human_matched_tids_set | (win_human_main_tids_set & win_human_sub_tids))

    for src, model, i, cc, cr, o in global_msg_usage.values():
        vec = [i, cc, cr, o]
        if src == "main":
            add_vec(tokens_main, vec)
        else:
            add_vec(tokens_sub, vec)
        add_vec(tokens_by_family[classify_model_family(model)], vec)

    # Finalize Metric 1
    trend_rows = []
    for mk in trend_month_list:
        md = trend_by_month[mk]
        trend_rows.append({
            "month": mk,
            "sessions": md["sessions"],
            "edits_code": md["edits_code"],
            "impl_dispatches": md["impl_dispatches"],
            "ratio_code_to_impl": ratio(md["edits_code"], md["impl_dispatches"]),
        })

    # Finalize Metric 2
    bursts_60m = [b for b in orch_bursts_all if b["code_edits_within_60m"] >= 3]
    bursts_60m_sorted = sorted(
        bursts_60m,
        key=lambda x: (-x["code_edits_within_60m"], -x["code_edits"], x["date"], x["sid8"]),
    )

    # Finalize Metric 3
    tot_delegations = sum(role_main_cats.values())
    roles_out = {}
    for rk in ROLE_ORDER:
        cnt = role_main_cats[rk]
        roles_out[rk] = {
            "label": ROLE_META_INFO[rk][0],
            "count": cnt,
            "pct": pct(cnt, tot_delegations),
        }

    # Finalize Metric 4
    tokens_combined = [tokens_main[i] + tokens_sub[i] for i in range(4)]
    tot_all = sum(tokens_combined)
    main_blk = {**fmt_token_block(tokens_main), "share_pct": pct(sum(tokens_main), tot_all)}
    sub_blk = {**fmt_token_block(tokens_sub), "share_pct": pct(sum(tokens_sub), tot_all)}
    comb_blk = fmt_token_block(tokens_combined)

    fam_out = {}
    for fam in MODEL_FAMILY_ORDER:
        arr = tokens_by_family[fam]
        fam_out[fam] = {
            **fmt_token_block(arr),
            "share_pct": pct(sum(arr), tot_all),
        }

    elapsed = round(time.time() - t0, 3)

    return {
        "meta": {
            "date": ref_date.isoformat(),
            "days": days,
            "trend_months": trend_months,
            "window_start_date": (ref_date - dt.timedelta(days=days - 1)).isoformat(),
            "projects_dir": str(projects_dir),
            "elapsed_seconds": elapsed,
        },
        "metric1_self_edit_vs_impl": {
            "orchestrator_only": {
                **orch,
                "ratio_code_to_impl": ratio(orch["edits_code"], orch["impl_dispatches"]),
            },
            "worker_only": {
                **wrk,
                "ratio_code_to_impl": ratio(wrk["edits_code"], wrk["impl_dispatches"]),
            },
            "trend_by_month": trend_rows,
        },
        "metric2_post_review_60m_bursts": {
            "pure_5_review_roles": sorted(PURE_CODE_REVIEW_ROLES),
            "orchestrator_only_episodes_ge3_within_60m": len(bursts_60m),
            "orchestrator_only_unique_sessions_within_60m": len({b["sid8"] for b in bursts_60m}),
            "orchestrator_only_episodes_ge3_any_window": len(orch_bursts_all),
            "top_samples": bursts_60m_sorted[:10],
        },
        "metric3_delegation_roles": {
            "human_interactive_sessions": win_sessions_human,
            "total_main_delegations": tot_delegations,
            "roles": roles_out,
            "subagent_meta_roles": {rk: role_sub_meta_cats[rk] for rk in ROLE_ORDER},
            "top_agent_types": dict(top_agent_types.most_common(15)),
        },
        "metric4_tokens_and_models": {
            "main": main_blk,
            "subagent": sub_blk,
            "combined": comb_blk,
            "by_model_family": fam_out,
        },
        "quality_receipt": {
            "total_all_time_main_jsonl": total_all_time,
            "scanned_main_jsonl": scanned_in_range,
            "window_sessions_total": win_sessions_total,
            "window_sessions_human": win_sessions_human,
            "window_sessions_orchestrator": orch["sessions"],
            "window_sessions_worker": wrk["sessions"],
            "excluded_automated_sessions": win_sessions_auto,
            "excluded_by_reason": dict(win_auto_by_reason),
            "scanned_subagent_jsonl": win_sub_jsonl,
            "skipped_main_files": skipped_main,
            "skipped_subagent_files": skipped_sub,
            "json_line_parse_errors": parse_errors_total,
            "cross_file_deduped_messages": cross_file_deduped_messages,
            "tool_use_id_crosscheck": {
                "main_agent_tids": win_main_tids,
                "matched_tids": win_matched_tids,
                "match_rate_pct": pct(win_matched_tids, win_main_tids),
                "human_main_agent_tids": win_human_main_tids,
                "human_matched_tids": win_human_matched_tids,
                "human_match_rate_pct": pct(win_human_matched_tids, win_human_main_tids),
            },
            "elapsed_seconds": elapsed,
        },
    }


