def classify_role(role: str) -> str:
    if role in JUDGE_ROLES:
        return "judge"
    if role in REVIEW_ROLES:
        return "review_verify"
    if role in IMPL_ROLES:
        return "impl"
    if role in RECON_ROLES:
        return "recon"
    return "other"


def classify_model_family(model: str) -> str:
    m = (model or "").lower()
    if not m or m == "<synthetic>":
        return "other"
    # gpt 家族可能帶 -pro（例如 gpt-5.4-pro），須先於 opus/pro 判斷
    if "gpt" in m or "codex" in m or "sol" in m or "terra" in m:
        return "gpt"
    if "argon" in m:
        return "argon"
    if "opus" in m or "gemini-pro" in m or "-pro" in m or "/pro" in m:
        return "opus/pro"
    if "sonnet" in m or "flash" in m:
        return "sonnet/flash"
    if "haiku" in m:
        return "haiku"
    return "other"


def classify_file_path(fp: str) -> str:
    if not fp:
        return "non_code"
    low = fp.lower()
    for sub in NON_CODE_PATH_SUBSTRS:
        if sub in low:
            return "non_code"
    base = os.path.basename(fp)
    if base in CODE_BASENAMES:
        return "code"
    _, ext = os.path.splitext(base)
    ext_l = ext.lower()
    if ext_l in CODE_EXTENSIONS:
        return "code"
    if ext_l in CONFIG_EXTENSIONS:
        return "config"
    return "non_code"


def parse_iso_ts(ts_val) -> float:
    if not ts_val or isinstance(ts_val, bool):
        return 0.0
    if isinstance(ts_val, (int, float)):
        val = float(ts_val)
        return val if math.isfinite(val) and val > 0 else 0.0
    if isinstance(ts_val, str):
        s = ts_val.strip()
        if not s:
            return 0.0
        if s.endswith(("Z", "z")):
            s = s[:-1] + "+00:00"
        try:
            val = dt.datetime.fromisoformat(s).timestamp()
            return val if math.isfinite(val) and val > 0 else 0.0
        except Exception:
            return 0.0
    return 0.0


